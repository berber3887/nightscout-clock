const DICTS = { fr: FR }

/**
 * The language in use: the one chosen with the header button, else the browser's when it is one we have.
 * @returns {string}
 */
function currentLang() {
    let saved = null
    try { saved = localStorage.getItem("ns_lang") } catch (e) { /* storage may be unavailable */ }
    if (saved && LANGS[saved]) return saved
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase()
    return DICTS[nav] ? nav : "en"
}

const LANG = currentLang()
// The dictionary with its keys trimmed: texts are matched without their surrounding whitespace.
const DICT = DICTS[LANG] ? Object.fromEntries(Object.entries(DICTS[LANG]).map(([k, v]) => [k.trim(), v.trim()])) : null
// Keys with ${n} placeholders become patterns; the others are looked up directly.
const PATTERNS = DICT ? Object.keys(DICT).filter(k => k.includes("${")).map(k => {
    const re = new RegExp("^" + k.replace(/[.*+?^()|[\]\\]/g, "\\$&").replace(/\\\$\\\{(\d+)\\\}|\$\{(\d+)\}/g, "([\\s\\S]*?)") + "$")
    return { re, to: DICT[k] }
}) : []

/**
 * Translate one text. The surrounding whitespace is kept; a text we do not know comes back unchanged.
 * @param {string} text - English text, possibly built from a template.
 * @returns {string}
 */
function t(text) {
    if (!DICT || typeof text !== "string") return text
    const lead = text.match(/^\s*/)[0], trail = text.match(/\s*$/)[0]
    const core = text.slice(lead.length, text.length - trail.length)
    if (!core) return text
    if (DICT[core] != null) return lead + DICT[core] + trail
    for (const { re, to } of PATTERNS) {
        const m = core.match(re)
        if (m) return lead + to.replace(/\$\{(\d+)\}/g, (_, i) => t(m[Number(i) + 1])) + trail
    }
    return text
}

/**
 * Apply the dictionary to the page as it is drawn: text nodes and the attributes people read.
 * @returns {void}
 */
function translatePage() {
    if (!DICT) return
    const ATTRS = ["placeholder", "aria-label", "title", "data-tip"]
    const written = new WeakMap()
    const fixText = node => {
        const now = node.data
        if (written.get(node) === now) return
        const fr = t(now)
        if (fr !== now) { written.set(node, fr); node.data = fr }
    }
    const fixAttrs = elm => {
        for (const a of ATTRS) {
            if (!elm.hasAttribute(a)) continue
            const v = elm.getAttribute(a), fr = t(v)
            if (fr !== v) elm.setAttribute(a, fr)
        }
    }
    const walk = root => {
        if (root.nodeType === Node.TEXT_NODE) return fixText(root)
        if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return
        if (root.nodeType === Node.ELEMENT_NODE) fixAttrs(root)
        const it = document.createNodeIterator(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
        for (let n = it.nextNode(); n; n = it.nextNode()) n.nodeType === Node.TEXT_NODE ? fixText(n) : fixAttrs(n)
    }
    document.documentElement.lang = LANG
    document.documentElement.setAttribute("translate", "no")
    walk(document)
    document.title = t(document.title)
    new MutationObserver(list => {
        for (const m of list) {
            if (m.type === "characterData") fixText(m.target)
            else if (m.type === "attributes") fixAttrs(m.target)
            else m.addedNodes.forEach(walk)
        }
    }).observe(document.documentElement, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS })
}

/**
 * Remember the language asked for and redraw the page in it.
 * @param {string} lang - "en" or "fr".
 * @returns {void}
 */
function setLang(lang) {
    try { localStorage.setItem("ns_lang", lang) } catch (e) { /* storage may be unavailable */ }
    location.reload()
}

